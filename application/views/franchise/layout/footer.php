                formAction.includes('/hotel') || 
                formAction.includes('flight') ||
                formAction.includes('hotel') ||
                formId.includes('flight') || 
                formId.includes('hotel') || 
                formClass.includes('flight') || 
                formClass.includes('hotel') ||
                formId === 'akbarhotelform' ||
                formId === 'hotelbookingform' ||
                formId === 'bookingform' ||
                formId === 'finalpaymentform' ||
                formId === 'roundtripform' ||
                formId === 'roundtripbookingform';

            if (isFlightOrHotel) {
                return; // NEVER INTERFERE WITH FLIGHT OR HOTEL PAGES!
            }

            // Check if it's an inquiry / lead / newsletter form
            const isEnquiryForm = 
                formAction.includes('submit_visa') || 
                formAction.includes('submit_holiday') || 
                formAction.includes('submit_forex') || 
                formAction.includes('submit_cruise') || 
                formAction.includes('submit_cab') || 
                formAction.includes('submit_enquiry') || 
                form.classList.contains('newsletter-form') || 
                formId.includes('newsletter') ||
                formId.includes('enquiry') || 
                formId.includes('forex') || 
                formId.includes('cruise') || 
                formId.includes('visa') ||
                formId.includes('cab') ||
                formId.includes('holiday') ||
                formAction.includes('contact') ||
                formId.includes('contact') ||
                formClass.includes('enquiry') ||
                formClass.includes('lead');

            if (isEnquiryForm) {
                e.preventDefault();

                // Quick handling for newsletter forms
                if (form.classList.contains('newsletter-form') || formId.includes('newsletter') || formAction.includes('subscribe')) {
                    const emailInput = form.querySelector('input[type="email"]');
                    const email = emailInput ? emailInput.value : '';
                    openVoyogoThankYouModal(
                        'Thank you for subscribing to Voyogo exclusive B2B updates! Check your inbox (' + (email || 'your email') + ') for promo codes and secret airfare drop alerts.',
                        'Subscription Confirmed'
                    );
                    form.reset();
                    return;
                }

                // Show loading state on submit button
                const submitBtn = form.querySelector('button[type="submit"], input[type="submit"]');
                const origBtnHtml = submitBtn ? submitBtn.innerHTML : '';
                if (submitBtn) {
                    submitBtn.disabled = true;
                    submitBtn.innerHTML = '<i class="fa-solid fa-spinner fa-spin"></i> Submitting...';
                }

                const formData = new FormData(form);
                fetch(form.action, {
                    method: 'POST',
                    body: formData,
                    headers: { 'X-Requested-With': 'XMLHttpRequest' }
                })
                .then(res => {
                    const ct = res.headers.get('content-type');
                    if (ct && ct.includes('application/json')) {
                        return res.json();
                    }
                    return { status: 'success' };
                })
                .then(data => {
                    let msg = data.message || '';
                    let badge = data.badge || 'Enquiry Received';

                    if (!msg) {
                        if (formAction.includes('submit_visa')) {
                            msg = 'Your Visa Application enquiry has been received! Our visa specialist will contact you shortly with checklist and processing details.';
                            badge = 'Visa Enquiry Confirmed';
                        } else if (formAction.includes('submit_holiday')) {
                            msg = 'Your Holiday Package enquiry has been received! Our tour expert will provide a custom itinerary shortly.';
                            badge = 'Holiday Enquiry Confirmed';
                        } else if (formAction.includes('submit_forex')) {
                            msg = 'Your Forex Order enquiry has been received! Our forex desk will call you with live locked currency rates.';
                            badge = 'Forex Order Confirmed';
                        } else if (formAction.includes('submit_cruise')) {
                            msg = 'Your Cruise Vacation enquiry has been received! Our cruise specialist will send available stateroom options shortly.';
                            badge = 'Cruise Enquiry Confirmed';
                        } else if (formAction.includes('submit_cab')) {
                            msg = 'Your Cab Booking enquiry has been received! Our transport team will confirm vehicle availability shortly.';
                            badge = 'Cab Booking Confirmed';
                        } else if (formAction.includes('submit_enquiry')) {
                            msg = 'Thank you! Your Franchise Enquiry has been submitted successfully. Our franchise development team will contact you shortly.';
                            badge = 'Franchise Enquiry Confirmed';
                        } else {
                            msg = 'Thank you for contacting Voyogo! Our travel team has received your enquiry and will connect with you shortly.';
                        }
                    }

                    openVoyogoThankYouModal(msg, badge);
                    form.reset();
                })
                .catch(() => {
                    openVoyogoThankYouModal(
                        'Thank you for contacting Voyogo! Our travel team has received your details and will get in touch shortly.',
                        'Enquiry Received'
                    );
                    form.reset();
                })
                .finally(() => {
                    if (submitBtn) {
                        submitBtn.disabled = false;
                        submitBtn.innerHTML = origBtnHtml;
                    }
                });
            }
        });
    });
